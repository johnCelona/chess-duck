"""Build backend/src/duckgambit/domain/minigames/pawn_races.py: proven pawn races.

    uv run --project backend python scripts/build_pawn_races.py

Every position is solved exactly (pawn_solver). Easy: White wins, with plenty of good
first moves. Hard: either White wins by few first moves, or White is losing but the hard
rival can still be held to a tie or beaten (checked by playing every line against it).
"""

import random
from pathlib import Path

import chess

from duckgambit.domain.minigames.base import moved
from duckgambit.domain.minigames.pawn_race import (
    HARD_DEPTH,
    race_moves,
    race_over,
    rival_move,
)
from duckgambit.domain.minigames.pawn_solver import race_of, solve

OUT = Path("backend/src/duckgambit/domain/minigames/pawn_races.py")
EASY, HARD = 40, 30  # HARD of each kind
rng = random.Random(20261124)


def deal(count):
    board = chess.Board(None)
    for color, ranks in (
        (chess.WHITE, (1, 1, 1, 2, 2, 3)),
        (chess.BLACK, (6, 6, 6, 5, 5, 4)),
    ):
        for file in rng.sample(range(8), count):
            square = chess.square(file, rng.choice(ranks))
            if board.piece_at(square):
                return None
            board.set_piece_at(square, chess.Piece(chess.PAWN, color))
    return board


def holdable(board, replies, seen, budget):
    """Can White reach a tie or a win against the hard rival's fixed replies?"""
    for move in race_moves(board):
        after = moved(board, move.uci())
        over = race_over(after)
        if over in ("white", "stuck"):
            return True
        key = after.epd()
        if key in seen or len(seen) > budget:
            continue
        seen.add(key)
        if key not in replies:
            replies[key] = rival_move(after, HARD_DEPTH).uci()
        after = moved(after, replies[key])
        over = race_over(after)
        if over == "stuck" or over == "white":
            return True
        if not over and holdable(after, replies, seen, budget):
            return True
    return False


def main():
    packs = {"EASY": [], "HARD_WINNING": [], "HARD_LOSING": []}
    tried = 0
    while (
        len(packs["EASY"]) < EASY
        or len(packs["HARD_WINNING"]) < HARD
        or len(packs["HARD_LOSING"]) < HARD
    ):
        tried += 1
        count = rng.choice([3, 3, 4])
        board = deal(count)
        if board is None or race_over(board):
            continue
        known = {}
        value = solve(race_of(board), known)
        moves = race_moves(board)
        good = sum(solve(race_of(moved(board, m.uci())), known) == -1 for m in moves)
        # A pawn with a free run from the start is no puzzle.
        free = any(
            chess.square_rank(s) >= 3
            and not any(
                abs(chess.square_file(t) - chess.square_file(s)) <= 1 and t > s
                for t in board.pieces(chess.PAWN, chess.BLACK)
            )
            for s in board.pieces(chess.PAWN, chess.WHITE)
        )
        fen = board.fen()
        if (
            value == 1
            and not free
            and good * 2 >= len(moves)
            and len(packs["EASY"]) < EASY
        ):
            packs["EASY"].append(fen)
        elif (
            value == 1
            and not free
            and good * 3 <= len(moves)
            and len(packs["HARD_WINNING"]) < HARD
        ):
            packs["HARD_WINNING"].append(fen)
        elif (
            value == -1
            and len(packs["HARD_LOSING"]) < HARD
            and holdable(board, {}, set(), 400)
        ):
            packs["HARD_LOSING"].append(fen)
        else:
            continue
        print(tried, {name: len(fens) for name, fens in packs.items()}, flush=True)
    lines = ['"""Generated by scripts/build_pawn_races.py. Do not edit by hand."""', ""]
    for name, fens in packs.items():
        lines += (
            [f"{name}: list[str] = ["] + [f'    "{fen}",' for fen in fens] + ["]", ""]
        )
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")


main()
